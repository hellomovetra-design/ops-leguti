const fs = require('node:fs'), vm = require('node:vm'), ts = require('typescript'), assert = require('node:assert/strict');
const m = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/employee-employment.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module: m, exports: m.exports });
const { employeeEmployment, EMPLOYMENT_LABELS } = m.exports;
for (const [value, expected] of [['PKWTT','permanent'],[' tetap ','permanent'],['PKWT','contract'],['Outsourcing','outsource'],['alih daya','outsource'],['FREELANCE','outsource'],['Freelancer','outsource'],['FL','outsource'],['Aktif','unknown'],['Nonaktif','unknown'],['Resign','unknown'],['','unknown'],[null,'unknown']]) {
  assert.equal(employeeEmployment({ employment: value }), expected);
}
assert.equal(employeeEmployment({ employment: 'FREELANCE', nik: 'TGRFL123' }), 'outsource');
assert.equal(employeeEmployment({ employment: 'PKWTT', active: false }), 'permanent');
assert.equal(Object.keys(EMPLOYMENT_LABELS).length, 4);
assert.equal('freelance' in EMPLOYMENT_LABELS, false);
const row = { employment: 'FREELANCE' };
employeeEmployment(row);
assert.equal(row.employment, 'FREELANCE', 'Display grouping must not mutate stored contract type');
const source = fs.readFileSync('components/employee-dashboard.tsx', 'utf8');
assert.ok(source.includes('employmentCounts=filterEmployees(rows,filters,"employment")'));
assert.ok(source.includes('filtered.slice(0,visibleCount)'));
assert.ok(source.includes('<th>Kepegawaian</th>'));
const topCards = source.slice(source.indexOf('<div className="employee-kpis'), source.indexOf('<div className="employee-summary-strip'));
assert.equal((topCards.match(/<button /g)||[]).length,6, 'Top row includes formation, motor, mobil, staff, leader and coordinator');
assert.ok(topCards.includes('onClick={()=>open("leader")}'));
assert.ok(topCards.includes('onClick={()=>open("coordinator")}'));
assert.ok(source.includes('className="employment-summary-filters"'));
assert.ok(source.includes('current===type?"all":type'), 'Selected employment category can be cleared');
assert.ok(!source.includes('className="employment-panel"'), 'No duplicate employment panel below the summary');
const strip=source.slice(source.indexOf('<div className="employee-summary-strip'));
assert.ok(strip.indexOf('openHub("SPC LEGUTI")')<strip.indexOf('openHub("SP MALOKO")'));
assert.ok(strip.indexOf('statusButton("active"')<strip.indexOf('statusButton("inactive"'));
assert.ok(strip.indexOf('statusButton("inactive"')<strip.indexOf('statusButton("resigned"'));
assert.ok(strip.indexOf('statusButton("resigned"')<strip.indexOf('className="employment-summary-filters"'));
assert.ok(strip.includes('["contract","permanent","outsource","unknown"]'));
const styles=fs.readFileSync('components/employee-status.css','utf8');
assert.ok(styles.includes('.employee-summary-strip.employee-overview-strip button[aria-pressed=true]{background:linear-gradient(135deg,#0759b7,#1686d9);color:#fff;'));
assert.ok(styles.includes('button[aria-pressed=true] .status-dot{color:#fff}'));
const statusButtonSource=source.split('\n').find(line=>line.includes('const statusButton='));
assert.ok(statusButtonSource.includes('className="status-summary"'), 'Avoid legacy .status-summary.active !important transparent override');
assert.ok(statusButtonSource.includes('aria-pressed={statusFilter===v}'));
console.log('PASS: freelance grouped as outsource, no standalone freelance category, original data preserved, independent lifecycle status and dashboard filters.');
